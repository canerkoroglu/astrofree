// Builds the offline world map from Natural Earth (public domain):
//   node scripts/build-worldmap.mjs [ne_50m_admin_0_countries.geojson ne_10m_admin_1_states_provinces.geojson]
// - land outline from world-atlas (land-50m)          -> src/renderer/src/assets/world.ts
// - country borders + names, province borders + names -> src/renderer/src/assets/world-detail.ts
// Map coordinates are equirectangular: x = lon + 180, y = 90 - lat.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature, mesh } from 'topojson-client'
import { topology } from 'topojson-server'
import { presimplify, simplify } from 'topojson-simplify'

const require = createRequire(import.meta.url)
const out = (name) => new URL(`../src/renderer/src/assets/${name}`, import.meta.url)

function toPath(lines, precision, close = false) {
  const f = 10 ** precision
  const r = (v) => Math.round(v * f) / f
  let d = ''
  for (const line of lines) {
    let prev = ''
    let n = 0
    let seg = ''
    for (const [lon, lat] of line) {
      const pt = `${r(lon + 180)} ${r(90 - lat)}`
      if (pt === prev) continue
      seg += (n === 0 ? 'M' : 'L') + pt
      prev = pt
      n++
    }
    if (n > 1) d += seg + (close ? 'Z' : '')
  }
  return d
}

// ---- land ----------------------------------------------------------------------
const landTopo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'))
const land = feature(landTopo, landTopo.objects.land)
const rings = []
for (const f of land.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  for (const p of polys) rings.push(...p)
}
const landPath = toPath(rings, 2, true)
writeFileSync(out('world.ts'), `// Generated by scripts/build-worldmap.mjs from Natural Earth (public domain).\nexport const WORLD_PATH =\n  '${landPath}'\n`)
console.log(`land ${(landPath.length / 1024).toFixed(0)} KB`)

// ---- countries and provinces -------------------------------------------------------
const [countriesPath, provincesPath] = process.argv.slice(2)
if (!countriesPath || !provincesPath) {
  console.log('country/province files not given; world-detail.ts left unchanged')
  process.exit(0)
}

function simplified(fc, key, minWeight) {
  let topo = topology({ [key]: fc }, 1e5)
  topo = presimplify(topo)
  return simplify(topo, minWeight)
}

const countries = JSON.parse(readFileSync(countriesPath, 'utf8'))
const ct = simplified(countries, 'c', 2e-4)
const borders = mesh(ct, ct.objects.c, (a, b) => a !== b)
const countryBorders = toPath(borders.coordinates, 2)
const countryLabels = countries.features
  .map((f) => {
    const p = f.properties
    return [+(+p.LABEL_X).toFixed(2), +(+p.LABEL_Y).toFixed(2), p.NAME_TR || p.NAME, Math.round(+p.MIN_LABEL || +p.LABELRANK || 5)]
  })
  .filter((l) => Number.isFinite(l[0]) && Number.isFinite(l[1]) && l[2])

const provinces = JSON.parse(readFileSync(provincesPath, 'utf8'))
// Drop tiny attributes before building the topology to save memory.
for (const f of provinces.features) {
  const p = f.properties
  f.properties = { c: p.adm0_a3, n: p.name_tr || p.name, x: p.longitude, y: p.latitude }
}
const pt = simplified(provinces, 'p', 5e-5)
const byCountry = new Map()
for (const g of pt.objects.p.geometries) byCountry.set(g.properties.c, true)
const provinceChunks = []
for (const code of byCountry.keys()) {
  const m = mesh(pt, pt.objects.p, (a, b) => a !== b && a.properties.c === code && b.properties.c === code)
  if (!m.coordinates.length) continue
  let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity]
  for (const line of m.coordinates)
    for (const [lon, lat] of line) {
      x0 = Math.min(x0, lon + 180)
      x1 = Math.max(x1, lon + 180)
      y0 = Math.min(y0, 90 - lat)
      y1 = Math.max(y1, 90 - lat)
    }
  provinceChunks.push({ b: [x0, y0, x1, y1].map((v) => +v.toFixed(2)), d: toPath(m.coordinates, 2) })
}
const provinceLabels = provinces.features
  .map((f) => [+(+f.properties.x).toFixed(2), +(+f.properties.y).toFixed(2), f.properties.n])
  .filter((l) => Number.isFinite(l[0]) && Number.isFinite(l[1]) && l[2])

const body = [
  '// Generated by scripts/build-worldmap.mjs from Natural Earth (public domain).',
  '// Loaded lazily by the world map.',
  `export const COUNTRY_BORDERS = '${countryBorders}'`,
  `/** [lon, lat, name, minZoomRank] */`,
  `export const COUNTRY_LABELS: [number, number, string, number][] = ${JSON.stringify(countryLabels)}`,
  `/** Province borders per country with their bounding box in map coordinates. */`,
  `export const PROVINCES: { b: [number, number, number, number]; d: string }[] = ${JSON.stringify(provinceChunks)}`,
  `/** [lon, lat, name] */`,
  `export const PROVINCE_LABELS: [number, number, string][] = ${JSON.stringify(provinceLabels)}`,
  ''
].join('\n')
writeFileSync(out('world-detail.ts'), body)
const provBytes = provinceChunks.reduce((s, c) => s + c.d.length, 0)
console.log(`countries ${(countryBorders.length / 1024).toFixed(0)} KB, ${countryLabels.length} labels; provinces ${provinceChunks.length} countries, ${(provBytes / 1024).toFixed(0)} KB, ${provinceLabels.length} labels; total ${(body.length / 1024).toFixed(0)} KB`)
