// Builds the offline world map (Natural Earth 50m land via world-atlas, public
// domain) as an equirectangular SVG path: x = lon + 180, y = 90 - lat.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)
const r = (v) => Math.round(v * 10) / 10
let d = ''
const ring = (coords) => {
  let prev = ''
  coords.forEach(([lon, lat], i) => {
    const pt = `${r(lon + 180)} ${r(90 - lat)}`
    if (pt === prev) return
    d += (i === 0 ? 'M' : 'L') + pt
    prev = pt
  })
  d += 'Z'
}
for (const f of land.features) {
  const g = f.geometry
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates
  for (const p of polys) for (const rg of p) ring(rg)
}
writeFileSync(
  new URL('../src/renderer/src/assets/world.ts', import.meta.url),
  `// Generated by scripts/build-worldmap.mjs from Natural Earth (public domain).\nexport const WORLD_PATH =\n  '${d}'\n`
)
console.log(`path length ${(d.length / 1024).toFixed(0)} KB`)
